// Bundles the shared @relay parser (tabs-app/packages/shared/src/relayCommand.ts)
// into a browser IIFE exposing window.RelayCommand. Run with Bun:
//   bun extensions/relay/scripts/gen-command.mjs
// Writes prototypes/relay/relay-command.js for the standalone preview. build.mjs reuses
// buildRelayCommand() so the packaged extension always matches the shared parser.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const entry = fileURLToPath(new URL('./relay-command-entry.ts', import.meta.url));
const output = fileURLToPath(new URL('../../../prototypes/relay/relay-command.js', import.meta.url));

export async function buildRelayCommand() {
  const result = await Bun.build({ entrypoints: [entry], format: 'iife', target: 'browser', minify: false });
  if (!result.success) throw new Error('Could not bundle relayCommand.ts: ' + result.logs.join('\n'));
  const code = await result.outputs[0].text();
  return '/* GENERATED by extensions/relay/scripts/gen-command.mjs from tabs-app/packages/shared/src/relayCommand.ts. Do not edit. */\n' + code;
}

if (import.meta.main) {
  await writeFile(output, await buildRelayCommand());
  console.log('Wrote ' + output);
}
